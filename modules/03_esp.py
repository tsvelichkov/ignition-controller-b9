def _crc8_autosar_h2f(data: bytes) -> int:
    """CRC-8 / AUTOSAR H2F (poly 0x2F, init 0xFF, xorout 0xFF)."""
    crc = 0xFF
    for b in data:
        crc ^= b
        for _ in range(8):
            if crc & 0x80:
                crc = ((crc << 1) ^ 0x2F) & 0xFF
            else:
                crc = (crc << 1) & 0xFF
    return crc ^ 0xFF


